#!/usr/bin/env node
/**
 * Generate the repo-root package.json, whose only job is to forward
 * `npm run <script>` into `barwise/`.
 *
 * The repo root holds exactly one directory -- `barwise/` -- and the only
 * package.json is inside it. So `npm run build` works one level down and
 * fails at the root with a bare ENOENT on a path the user never typed.
 * That is a small papercut on its own and a real defect in aggregate: it
 * was the direct cause of five broken commands in a single session, and
 * indirectly of a WRONG CLAIM, because the habit it trains -- "run it
 * from wherever, see what happens" -- is what produced a `check:shell`
 * result quoted as CI's when CI's number was different (barwise-907).
 *
 * The alternative fix is to flatten the layout so the monorepo sits at
 * the root. That touches every path in ci.yml, every doc, and every spec,
 * to remove one `cd`. This forwards instead.
 *
 * WHY GENERATED. The forwarder list must agree with `barwise/package.json`
 * or it is worse than absent: a stale entry runs nothing, and a missing
 * one restores the papercut for exactly the newest script. CLAUDE.md
 * forbids a must-agree copy guarded by a comment, so this derives the
 * list from the authority and `--check` fails on drift in either
 * direction -- a script added to barwise/ with no forwarder, and a
 * forwarder for a script that no longer exists.
 *
 * The comparison is on the parsed `scripts` object, not on bytes, so
 * whitespace is this script's business and never a CI failure.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { REPO_ROOT } from "./lib/tracked.mjs";

const INNER = resolve(REPO_ROOT, "barwise/package.json");
const ROOT = resolve(REPO_ROOT, "package.json");

/**
 * npm runs these itself, on install and publish. A forwarded `prepare`
 * means `npm install` at the repo root silently runs husky setup for a
 * package that is not installable -- the root is a signpost, not a
 * project, and must not behave like one.
 */
const LIFECYCLE = new Set([
  "prepare",
  "preinstall",
  "install",
  "postinstall",
  "prepublishOnly",
  "prepack",
  "postpack",
  "prepublish",
]);

function forwarders() {
  const inner = JSON.parse(readFileSync(INNER, "utf8"));
  const out = {};
  for (const name of Object.keys(inner.scripts ?? {})) {
    if (LIFECYCLE.has(name)) continue;
    // The trailing `--` is what makes `npm run check:beads -- --strict`
    // reach the inner script as an argument instead of being eaten by
    // the outer npm as one of its own flags.
    out[name] = `npm --prefix barwise run ${name} --`;
  }
  return out;
}

function render(scripts) {
  return `${
    JSON.stringify(
      {
        name: "barwise-repo",
        private: true,
        "//": [
          "GENERATED by barwise/scripts/regen-root-package.mjs -- do not edit by hand.",
          "The real package.json is barwise/package.json; this only forwards to it",
          "so `npm run <script>` works from the repo root as well as from barwise/.",
          "Regenerate with: node barwise/scripts/regen-root-package.mjs",
        ],
        scripts,
      },
      null,
      2,
    )
  }\n`;
}

const wanted = forwarders();

if (process.argv.includes("--check")) {
  let actual;
  try {
    actual = JSON.parse(readFileSync(ROOT, "utf8")).scripts ?? {};
  } catch {
    console.error(
      "check:root-scripts: no readable package.json at the repo root.\n"
        + "  Run: node barwise/scripts/regen-root-package.mjs",
    );
    process.exit(1);
  }
  const missing = Object.keys(wanted).filter((k) => actual[k] !== wanted[k]);
  const stale = Object.keys(actual).filter((k) => !(k in wanted));
  if (missing.length > 0 || stale.length > 0) {
    if (missing.length > 0) console.error(`  missing or wrong: ${missing.join(", ")}`);
    if (stale.length > 0) {
      console.error(`  stale (not in barwise/package.json): ${stale.join(", ")}`);
    }
    console.error(
      "\ncheck:root-scripts: the root forwarders disagree with barwise/package.json.\n"
        + "  Run: node barwise/scripts/regen-root-package.mjs",
    );
    process.exit(1);
  }
  console.log(`check:root-scripts: ${Object.keys(wanted).length} forwarders agree. OK`);
} else {
  writeFileSync(ROOT, render(wanted));
  console.log(`wrote ${ROOT} (${Object.keys(wanted).length} forwarders)`);
}
